import {chromium} from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true})
try{
 const page=await browser.newPage({viewport:{width:900,height:600}}),errors=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.route('**/scripture-fixture',route=>route.fulfill({contentType:'text/html',body:'<div id="fixture" style="height:550px;display:flex;flex-direction:column"></div>'}))
 await page.addInitScript(()=>{window.api={send:()=>{},receive:()=>{},removeListener:()=>{}}})
 await page.goto('http://127.0.0.1:3000/scripture-fixture')
 await page.evaluate(async()=>{
  await import('/src/frontend/App.svelte')
  const stores=window.fixtureStores=await import('/src/frontend/stores.ts')
  stores.outputs.set({center:{name:'Center',enabled:true,active:true,out:{}},side:{name:'Side',enabled:true,out:{}},disabled:{name:'Disabled',enabled:false,out:{}},stage:{name:'Stage',enabled:true,stageOutput:true,out:{}}})
  stores.scriptureSettings.update(settings=>({...settings,outputIds:undefined,singleClickToDisplay:true}))
  const module=await import('/src/frontend/components/drawer/bible/Scripture.svelte')
  window.fixtureComponent=new module.default({target:document.querySelector('#fixture'),props:{active:null,searchValue:''}})
 })
 await page.getByRole('checkbox',{name:'Center',exact:true}).waitFor()
 assert.equal(await page.getByRole('combobox',{name:/Scripture.*(output|gesture)/i}).count(),0)
 assert.equal(await page.getByRole('checkbox',{name:'Center',exact:true}).getAttribute('aria-checked'),'true')
 assert.equal(await page.getByRole('checkbox',{name:'Side',exact:true}).getAttribute('aria-checked'),'false')
 assert.equal(await page.getByRole('checkbox',{name:'Stage',exact:true}).count(),0)
 assert.equal(await page.getByRole('checkbox',{name:'Disabled',exact:true}).count(),0)
 await page.getByRole('checkbox',{name:'Side',exact:true}).click()
 await page.getByRole('checkbox',{name:'Center',exact:true}).click()
 assert.deepEqual(await page.evaluate(()=>{let value;fixtureStores.scriptureSettings.subscribe(settings=>value=settings.outputIds)();return value}),['side'])
 await page.getByRole('button',{name:'Scripture outputs',exact:true}).click()
 assert.equal(await page.getByRole('checkbox',{name:'Side',exact:true}).count(),0)
 assert.deepEqual(await page.evaluate(()=>{let value;fixtureStores.scriptureSettings.subscribe(settings=>value=settings.outputIds)();return value}),['side'])
 await page.getByRole('button',{name:'Scripture outputs',exact:true}).click()
 await page.getByRole('checkbox',{name:'Side',exact:true}).waitFor()
 await page.evaluate(async()=>{const module=await import('/src/frontend/components/drawer/info/ScriptureInfo.svelte');const target=document.createElement('div');document.body.append(target);window.previewComponent=new module.default({target,props:{optionsOpen:false}})})
 assert.equal(await page.locator('.scripture-preview-routing').count(),0)
 assert.equal(await page.getByRole('checkbox',{name:'Side',exact:true}).count(),1)
 await page.getByRole('checkbox',{name:'Side',exact:true}).click()
 await page.getByText('Select an enabled output to display Scripture.',{exact:true}).waitFor()
 assert.deepEqual(await page.evaluate(()=>{let value;fixtureStores.scriptureSettings.subscribe(settings=>value=settings.outputIds)();return value}),[])
 const routing=await page.locator('.scripture-output-selection').boundingBox()
 const picker=await page.locator('#fixture > .scroll').boundingBox()
 assert.ok(routing.y < picker.y,'Output row should be above the Scripture picker')
 await page.getByRole('button',{name:'Display Scripture preview',exact:true}).waitFor()
 await page.evaluate(()=>{fixtureComponent.$destroy();previewComponent.$destroy()})
 assert.deepEqual(errors,[])
 console.log('PASS: Scripture output selector uses store keys, shows tick boxes without dropdowns, shares selections with the preview, and preserves empty selections')
}finally{await browser.close()}

